#!/bin/bash
# ============================================================================
# clean-fillers.sh
# 議事録テキストからフィラーワード（言い淀み）を削除する
# ============================================================================
#
# 【使用方法】
#   ./clean-fillers.sh <入力ファイル> <出力ファイル>
#
# 【削除対象】
#   - 日本語フィラー: えーと、あのー、まぁ、うーん、etc.
#   - 英語フィラー: um, uh, well, like, etc.
#   - 繰り返し: あの、あの、 → あの、
#   - 不要な空行
#

set -e

# ============================================================================
# 引数チェック
# ============================================================================
if [ $# -lt 2 ]; then
    echo "使用方法: $0 <入力ファイル> <出力ファイル>"
    exit 1
fi

INPUT_FILE="$1"
OUTPUT_FILE="$2"

if [ ! -f "$INPUT_FILE" ]; then
    echo "エラー: 入力ファイルが見つかりません: $INPUT_FILE"
    exit 1
fi

# ============================================================================
# フィラー削除処理
# ============================================================================

# 一時ファイル
TEMP_FILE=$(mktemp)

# Step 1: 基本的なフィラーワード削除（日本語）
cat "$INPUT_FILE" | \
    # 文頭・文中のフィラー
    sed 's/えーと[、,]* *//g' | \
    sed 's/えーっと[、,]* *//g' | \
    sed 's/えっと[、,]* *//g' | \
    sed 's/あのー[、,]* *//g' | \
    sed 's/あの[、,]* *//g' | \
    sed 's/えー[、,]* *//g' | \
    sed 's/まぁ[、,]* *//g' | \
    sed 's/まあ[、,]* *//g' | \
    sed 's/うーん[、,]* *//g' | \
    sed 's/うん[、,]* *//g' | \
    sed 's/そのー[、,]* *//g' | \
    sed 's/なんか[、,]* *//g' | \
    sed 's/ちょっと[、,]* *//g' | \
    sed 's/やっぱり[、,]* *//g' | \
    sed 's/やっぱ[、,]* *//g' | \
    sed 's/なんていうか[、,]* *//g' | \
    sed 's/何て言うか[、,]* *//g' | \
    sed 's/というか[、,]* *//g' | \
    sed 's/っていうか[、,]* *//g' | \
    sed 's/みたいな[、,]* *//g' | \
    # 語尾のフィラー
    sed 's/[、,] *ですかね[。.]*/.../g' | \
    sed 's/[、,] *かな[。.]*/.../g' | \
    # 英語フィラー
    sed 's/[Uu]m[,.]* *//g' | \
    sed 's/[Uu]h[,.]* *//g' | \
    sed 's/[Ww]ell[,.]* *//g' | \
    sed 's/[Ll]ike[,.]* *//g' | \
    sed 's/[Yy]ou know[,.]* *//g' | \
    sed 's/[Ss]o[,.]* *//g' | \
    # 連続する読点を1つに
    sed 's/[、,][、,]*/、/g' | \
    # 文頭の読点を削除
    sed 's/^[、,] *//g' | \
    # 連続する空白を1つに
    sed 's/  */ /g' | \
    # 空行を削除（連続する空行を1つに）
    cat -s \
    > "$TEMP_FILE"

# Step 2: タイムスタンプ行のクリーンアップ（Google Meets形式）
# 例: "00:05:23 田中太郎" → そのまま保持
# 例: "田中太郎 00:05:23" → そのまま保持

# Step 3: 出力
mv "$TEMP_FILE" "$OUTPUT_FILE"

# 処理結果のサマリー
INPUT_LINES=$(wc -l < "$INPUT_FILE" | tr -d ' ')
OUTPUT_LINES=$(wc -l < "$OUTPUT_FILE" | tr -d ' ')
INPUT_CHARS=$(wc -c < "$INPUT_FILE" | tr -d ' ')
OUTPUT_CHARS=$(wc -c < "$OUTPUT_FILE" | tr -d ' ')

REMOVED_CHARS=$((INPUT_CHARS - OUTPUT_CHARS))
REDUCTION_PERCENT=$((REMOVED_CHARS * 100 / INPUT_CHARS))

# 呼び出し元スクリプトがある場合は静かに終了
if [ -z "$VERBOSE" ]; then
    exit 0
fi

echo "フィラー削除完了:"
echo "  入力: ${INPUT_LINES} 行, ${INPUT_CHARS} 文字"
echo "  出力: ${OUTPUT_LINES} 行, ${OUTPUT_CHARS} 文字"
echo "  削減: ${REMOVED_CHARS} 文字 (${REDUCTION_PERCENT}%)"
